export const allPrograms: Program[] = programs.map((program) => {
  const slug = program.title
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

  return {
    ...program,
    slug,
    eligibilityUrl: `/programs/${slug}#eligibility`,
    applyUrl: `/apply-now?program=${slug}`,
    detailsUrl: `/programs/${slug}`,
  };
});
